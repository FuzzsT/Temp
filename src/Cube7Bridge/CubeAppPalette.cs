    public static int Count => Colors.Length;
    public static IReadOnlyList<CubeRgb> Entries => Colors;

    public static int IndexOfExact(byte r, byte g, byte b)
    {
        for (int i = 0; i < Colors.Length; i++)
        {
            var c = Colors[i];
            if (c.R == r && c.G == g && c.B == b) return i;
        }
        return -1;
    }

    public static int FindNearestIndex(byte r, byte g, byte b)
    {
        int exact = IndexOfExact(r, g, b);
        if (exact >= 0) return exact;

        int best = 0;
        int bestDistance = int.MaxValue;
        for (int i = 0; i < Colors.Length; i++)
        {
            var c = Colors[i];
            int dr = r - c.R;
            int dg = g - c.G;
            int db = b - c.B;
            int d = dr * dr + dg * dg + db * db;
            if (d < bestDistance)
            {
                bestDistance = d;
                best = i;
            }
        }
        return best;
    }
